_SCRIPT = """
<script>
const DATA = %s;
const IMAGES = {};
function loadImages(cb) {
  let pending = 0;
  for (const name in DATA.assets) {
    pending += 1;
    const img = new Image();
    img.onload = function () { IMAGES[name] = img; pending -= 1; if (!pending) cb(); };
    img.src = DATA.assets[name];
  }
  if (!pending) cb();
}
function drawScene(canvas, scene) {
  const ctx = canvas.getContext('2d');
  const W = canvas.width, H = canvas.height;
  ctx.fillStyle = '#1c1c26';
  ctx.fillRect(0, 0, W, H);
  if (!scene.sprites.length) {
    ctx.fillStyle = '#6a6a80';
    ctx.font = '14px monospace';
    ctx.textAlign = 'center';
    ctx.fillText('(empty scene)', W / 2, H / 2);
    return;
  }
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const s of scene.sprites) {
    const img = IMAGES[s.asset];
    const w = (img ? img.width : 12) * s.scale;
    const h = (img ? img.height : 12) * s.scale;
    minX = Math.min(minX, s.x - w / 2); maxX = Math.max(maxX, s.x + w / 2);
    minY = Math.min(minY, s.y - h / 2); maxY = Math.max(maxY, s.y + h / 2);
  }
  const worldW = Math.max(1, maxX - minX), worldH = Math.max(1, maxY - minY);
  const scale = Math.min(W / worldW, H / worldH, 24 / Math.max(1, scene.grid || 32));
  const pad = 8;
  const tx = (wx) => W / 2 + (wx - (minX + maxX) / 2) * scale;
  const ty = (wy) => H / 2 + (wy - (minY + maxY) / 2) * scale;
  ctx.strokeStyle = '#262633';
  ctx.lineWidth = 1;
  const cell = Math.max(2, Math.round((scene.grid || 32) * scale));
  for (let gx = minX; gx <= maxX; gx += (scene.grid || 32)) {
    ctx.beginPath(); ctx.moveTo(tx(gx), 0); ctx.lineTo(tx(gx), H); ctx.stroke();
  }
  for (let gy = minY; gy <= maxY; gy += (scene.grid || 32)) {
    ctx.beginPath(); ctx.moveTo(0, ty(gy)); ctx.lineTo(W, ty(gy)); ctx.stroke();
  }
  const ordered = scene.sprites.slice().sort((a, b) => a.layer - b.layer);
  for (const s of ordered) {
    if (!s.visible) continue;
    const img = IMAGES[s.asset];
    if (!img) continue;
    ctx.save();
    ctx.translate(tx(s.x), ty(s.y));
    ctx.scale(s.scale * (s.flip_h ? -1 : 1), s.scale * (s.flip_v ? -1 : 1));
    ctx.drawImage(img, -img.width / 2, -img.height / 2);
    ctx.restore();
  }
}
function render() {
  document.querySelectorAll('section.scene').forEach(function (section) {
    const canvas = section.querySelector('canvas');
    const key = canvas.dataset.key;
    const scene = DATA.scenes.find(function (s) { return s.id === key; });
    if (scene) drawScene(canvas, scene);
  });
}
window.addEventListener('load', loadImages.bind(null, render));
</script>
"""


def data_uri(data: bytes, mime: str = "image/png") -> str:
    return f"data:{mime};base64,{base64.b64encode(data).decode('ascii')}"


def image_data_uris(project: DexProject) -> dict[str, str]:
    """Map asset filename -> PNG data URI for every image asset."""
    uris: dict[str, str] = {}
    for entry in project.assets:
        if entry.kind != "image":
            continue
        path = os.path.join(project.assets_dir(), entry.filename)
        try:
            with open(path, "rb") as handle:
                data = handle.read()
        except OSError:
            continue
        try:
            if path.lower().endswith(".bmp"):
                width, height, rows = decode(data)
                data = encode_png(width, height, rows)
            else:
                decode(data)  # validate before embedding
            uris[entry.filename] = data_uri(data)
        except Exception:
            continue
    return uris


def build_html(project: DexProject) -> str:
    uris = image_data_uris(project)
    scenes = []
    for scene in project.scenes:
        sprites = []
        for sprite in scene.sprites:
            sprites.append(
                {
                    "asset": sprite.asset,
                    "x": sprite.x,
                    "y": sprite.y,
                    "layer": sprite.layer,
                    "scale": sprite.scale,
                    "flip_h": bool(sprite.flip_h),
                    "flip_v": bool(sprite.flip_v),
                    "visible": bool(sprite.visible),
                }
            )
        scenes.append({"id": scene.name, "name": scene.name, "grid": scene.grid,
                       "sprites": sprites})

    body: list[str] = []
    for scene in scenes:
        body.append(
            f'<section class="scene"><h2>Scene: {escape(scene["name"])}</h2>'
            f'<canvas data-key="{escape(scene["id"])}" width="900" height="560"></canvas></section>'
        )

    body.append("<h2>Assets</h2>")
    if uris:
        rows = "".join(
            f'<li><img src="{uri}" alt="{escape(name)}"><span>{escape(name)}</span></li>'
            for name, uri in uris.items()
        )
        body.append(f'<ul class="assets">{rows}</ul>')
    else:
        body.append('<p class="meta">No image assets.</p>')

    summary = (
        f"{len(project.scenes)} scene{'s' if len(project.scenes) != 1 else ''}, "
        f"{len(project.assets)} asset{'s' if len(project.assets) != 1 else ''}"
    )
    script = _SCRIPT % json.dumps(
        {"scenes": scenes, "assets": uris}, separators=(",", ":")
    )
    return (
        _HEAD.format(title=PAGE_TITLE, project=escape(project.name), summary=summary)
        + "".join(body)
        + _FOOT
        + script
    )


def render_project(project_root: str, out_dir: str | None = None) -> str:
    """Render ``project_root`` to ``index.html``; returns the file path."""
    project = DexProject.load(project_root)
    out_dir = out_dir or os.path.join(project_root, ".dexview")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "index.html")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(build_html(project))
    return path


def escape(value: str) -> str:
    """Escape text for safe inclusion in HTML."""
    return (
        str(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


